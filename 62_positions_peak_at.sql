-- ============================================================================
-- STOCK RADAR · positions.peak_at 컬럼 추가 (고점 발생 시각)
-- ============================================================================
-- 배경: 지금까지 peak_price/peak_date는 장마감 후 배치(06_portfolio.py)가
-- 일봉 데이터로 "그날의 고가"만 하루 단위로 기록했습니다. 이제 relay-server가
-- 웹소켓 실시간 체결가로 장중 고점을 그때그때 갱신하면서, 정확히 몇 시
-- 몇 분에 고점을 찍었는지도 함께 기록합니다(전략성과 "보유 중" 표의
-- "고점시각" 컬럼에 표시).
--
-- 주의: VIRTUAL 포트폴리오는 06_portfolio.py가 실행될 때마다 전 기간을
-- 통째로 삭제 후 재생성합니다(deterministic replay). 배치는 일봉 데이터만
-- 가지고 있어 정확한 분단위 시각을 알 수 없으므로, 배치가 재계산한 날은
-- peak_at을 그날 15:30(장마감 근사치) KST로 채웁니다. 즉 "오늘" 하루 동안은
-- relay-server가 기록한 정확한 분단위 값이 보이다가, 그날 밤 배치가 한 번
-- 더 돌고 나면 그 정밀도는 15:30 근사치로 대체됩니다 — 장중 실시간 모니터링
-- 용도로는 충분하지만, 분단위 이력을 영구 보존하려면 별도 로그 테이블이
-- 추가로 필요합니다(현재 범위 밖).
--
-- ⚠ 실행: Supabase SQL Editor에 붙여넣기 1회 실행.
-- ============================================================================

alter table positions add column if not exists peak_at timestamptz;

comment on column positions.peak_at is
  '고점(peak_price)이 기록된 시각. relay-server가 장중 실시간 체결가로 분단위
   정확하게 갱신하고, 06_portfolio.py 배치가 그 날을 재계산할 때는 정확한
   시각을 모르므로 그날 15:30:00 KST(장마감 근사치)로 대체 기록합니다.';
